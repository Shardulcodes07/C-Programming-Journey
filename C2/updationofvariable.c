/*2.Updation of variable*/
#include<stdio.h>
int main(){
    int x = 6;
    printf("The value is %d currently\n",x);
     x = 21;
    printf("The value has been updated to %d\n",x);
     x = 30;
    printf("The value has been updated to %d",x);
    return 0;
}

//int = %d is used for integer/int