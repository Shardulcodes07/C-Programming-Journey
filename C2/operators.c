// Non user input
#include<stdio.h>
int main(){
    int x = 5;
    int y = 2;
    printf("Addition = %d\n",x+y);
    printf("Subtraction = %d\n",x-y);
    printf("Multiplication = %d\n",x*y);
    printf("Division = %d\n",x/y);
    printf("Modulus = %d",x%y);
    return 0;
}